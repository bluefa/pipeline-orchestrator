package com.bff.pipeline.enums;

/**
 * 승인 요청 한 건의 생애 상태다(승인 게이트 ADR §결정 4). 모든 행은 {@code REQUESTED}에서 출발하고,
 * 나머지 네 값은 전부 종단이라 되돌아가지 않는다 — 다시 승인을 받으려면 파이프라인을 재시작해 새 게이트
 * 태스크와 새 승인 행을 만든다.
 *
 * 이 값이 게이트 태스크의 전이를 정하는 유일한 입력이다(만료 시각과 함께). 상태를 바꾸는 모든 쓰기는
 * "지금 REQUESTED일 때만 바꾼다"는 조건부 UPDATE라, 승인 클릭과 만료 처리가 동시에 들어와도 먼저 커밋한
 * 쪽 하나만 통과한다. 콘솔과 Slack이 같은 경로를 쓰므로 채널이 늘어도 판정 규칙은 한 곳이다.
 */
public enum ApprovalStatus {
    /** 승인을 기다리는 상태. 모든 결정 전이의 출발점이며 유일한 비종단 값이다. */
    REQUESTED,
    /** 사람이 승인했다. 게이트 태스크는 DONE이 되고 다음 단계가 진행된다. */
    APPROVED,
    /** 사람이 반려했다. 파이프라인 취소 요청이 함께 세워져 실행 전체가 CANCELLED로 닫힌다. */
    REJECTED,
    /** 만료 시각까지 아무 결정도 없었다. 게이트 태스크는 APPROVAL_EXPIRED로 실패한다. */
    EXPIRED,
    /** 결정 전에 파이프라인이 취소돼 요청 자체가 무의미해졌다. */
    CANCELLED
}
