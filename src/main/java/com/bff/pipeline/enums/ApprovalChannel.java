package com.bff.pipeline.enums;

/**
 * 승인·반려가 들어온 경로다(승인 게이트 ADR §결정 7). 감사 기록의 일부라 결정과 같은 행에 남는다 —
 * "누가 승인했는가"만큼 "어디서 승인했는가"도 사후 추적에 필요하기 때문이다.
 *
 * 두 경로는 판정 로직을 공유한다. 어느 쪽으로 들어오든 같은 조건부 UPDATE 한 번을 거치므로, 콘솔과
 * Slack에서 동시에 눌러도 통과는 한 건뿐이고 이 값이 그 한 건의 출처를 남긴다.
 */
public enum ApprovalChannel {
    /** 관리자 콘솔의 승인 화면. 관리자 권한 확인과 승인자 신원 주입은 BFF가 맡는다. */
    CONSOLE,
    /** 관리자 전용 Slack 채널의 승인 버튼. 채널 멤버십이 곧 권한이다. */
    SLACK
}
