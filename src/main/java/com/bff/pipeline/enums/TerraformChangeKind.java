package com.bff.pipeline.enums;

/**
 * terraform plan이 리소스 한 건에 대해 하겠다고 적은 일이다. 승인 화면이 "무엇이 몇 건 생기고 몇 건
 * 사라지는가"를 보여주기 위해 쓰는 분류이며, 실행에는 관여하지 않는다.
 *
 * 선언 순서가 곧 위험 순서다. 요약이 주소 목록을 컬럼 한도에 맞춰 줄여야 할 때 앞쪽부터 남기므로,
 * 되돌리기 비싼 변경(교체·삭제)이 먼저 오고 무해한 변경(수정·이동)이 뒤에 온다. 순서를 바꾸면 목록이
 * 잘렸을 때 승인자가 정작 봐야 할 것을 못 보게 된다.
 */
public enum TerraformChangeKind {
    /** 지웠다 다시 만든다. plan 합계 줄에는 자기 항목이 없고 생성·삭제로 흩어져 적힌다. */
    REPLACE,
    /** 지운다. */
    DESTROY,
    /** 실물은 두고 terraform 관리에서만 뺀다(1.7+의 removed 블록). */
    FORGET,
    /** 이미 있는 실물을 terraform 관리로 들인다. */
    IMPORT,
    /** 새로 만든다. */
    CREATE,
    /** 제자리에서 고친다. */
    UPDATE,
    /** 실물은 그대로 두고 주소만 옮긴다. plan 합계 줄에 나오지 않는다. */
    MOVE
}
